-- ========================================================================
-- 0062：删除职位映射 roster_title_map 中所有「HR 角色」映射（role='hr'）
--
-- 背景：0054 把一批管理/职能岗位（厂长/主任/经理/工程师/主管/办公室/安全员…，共
--   34 条）统一映射为 role='hr'。这会让「转为员工花名册」时把这些生产管理岗误设为
--   人事(hr)角色、授予 HR 权限。现按要求把这些 HR 相关映射从字典中去除：
--   转花名册时这些 title 不再命中本表，不写 role（保留 HR 在页面手工设定的角色）。
-- 范围：仅删 roster_title_map 内 role='hr' 的行，不影响已落地员工的 employee.role。
-- ========================================================================

DELETE FROM public.roster_title_map WHERE role = 'hr';
