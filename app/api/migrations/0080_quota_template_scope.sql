-- 记录地区设备类型模板是否已初始化，使“有意清空”不会再次回退到历史全局模板。
CREATE TABLE IF NOT EXISTS public.quota_template_scope (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region character varying(64) NOT NULL,
    furnace_type_code character varying NOT NULL
        REFERENCES public.furnace_type(code),
    CONSTRAINT quota_template_scope_region_furnace_type_key
        UNIQUE (region, furnace_type_code)
);

COMMENT ON TABLE public.quota_template_scope IS
    '地区设备类型模板初始化标记；存在时即使 quota_template 无行也不回退全局模板';
